Tests.EqualCheck("match lowercase letter in [a-zA-Z]", true, matchPattern("hello", "[a-zA-Z]ello"))
Tests.EqualCheck("do not match digit in [a-zA-Z]", false, matchPattern("1ello", "[a-zA-Z]ello"))
Tests.EqualCheck("match alphanumeric in [a-zA-Z0-9]", true, matchPattern("val_9", "val_[a-zA-Z0-9]"))
Tests.EqualCheck("match uppercase in [a-zA-Z0-9]", true, matchPattern("val_X", "val_[a-zA-Z0-9]"))
Tests.EqualCheck("do not match special char in [a-zA-Z0-9]", false, matchPattern("val_!", "val_[a-zA-Z0-9]"))
Tests.EqualCheck("match hex uppercase digit", true, matchPattern("0x3F", "0x[0-9a-fA-F][0-9a-fA-F]"))
Tests.EqualCheck("match hex lowercase digit", true, matchPattern("0x3f", "0x[0-9a-fA-F][0-9a-fA-F]"))
Tests.EqualCheck("do not match non-hex character", false, matchPattern("0x3Z", "0x[0-9a-fA-F][0-9a-fA-F]"))
Tests.EqualCheck("match literal underscore in mixed range [a-z0-9_]", true, matchPattern("foo_bar", "foo[a-z0-9_]bar"))
Tests.EqualCheck("match trailing literal hyphen in [a-z-]", true, matchPattern("foo-bar", "foo[a-z-]bar"))
Tests.EqualCheck("match leading literal hyphen in [-a-z]", true, matchPattern("foo-bar", "foo[-a-z]bar"))
Tests.EqualCheck("do not match char outside trailing hyphen group", false, matchPattern("foo_bar", "foo[a-z-]bar"))
Tests.EqualCheck("match multiple ranges with token sequence", true, matchPattern("ID: AB-12", "ID: [A-Z][A-Z]-[0-9][0-9]"))
Tests.EqualCheck("do not match when sequence length exceeds line", false, matchPattern("A", "[A-Z][A-Z]"))
Tests.EqualCheck("empty pattern matches any line", true, matchPattern("hello", ""))
